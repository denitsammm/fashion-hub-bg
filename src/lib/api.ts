export async function fetchTopDeals(minStores: number = 2): Promise<CanonicalProduct[]> {
  try {
    const res = await fetch(`${API_BASE_URL}/api/deals?min_stores=${minStores}`, {
      next: { revalidate: 30 }
    });
    if (!res.ok) throw new Error("API response not ok");
    const data = await res.json();
    return data && data.length > 0 ? data : SEED_DEALS;
  } catch (err) {
    return SEED_DEALS;
  }
}

export async function searchProducts(query: string): Promise<CanonicalProduct[]> {
  try {
    const res = await fetch(`${API_BASE_URL}/api/search?q=${encodeURIComponent(query)}`);
    if (!res.ok) throw new Error("Search API error");
    const data = await res.json();
    if (data && data.length > 0) return data;
  } catch (err) {
    // fallback
  }

  const q = query.toLowerCase().trim();
  return SEED_DEALS.filter(
    d => d.brand.toLowerCase().includes(q) || d.title.toLowerCase().includes(q)
  );
}
